-- V2: Create the decks table (flashcard sets owned by users).
-- Matches com.example.quizlet.entity.Deck

CREATE TABLE decks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150)  NOT NULL,
    description VARCHAR(1000),
    category    VARCHAR(100),
    creator_id  BIGINT        NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    is_public   BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_decks_creator FOREIGN KEY (creator_id) REFERENCES users (id)
);

-- Lookup by owner (GET /api/decks/me)
CREATE INDEX idx_decks_creator_id ON decks (creator_id);

-- Public-deck search scans
CREATE INDEX idx_decks_is_public ON decks (is_public);
