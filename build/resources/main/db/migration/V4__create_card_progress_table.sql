-- V4: Per-user learning progress for each card.
-- One row per (user, card); no row = implicitly NOT_LEARNED.
-- Matches the in-memory state machine in com.example.quizlet.learning.

CREATE TABLE card_progress (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL,
    card_id             BIGINT      NOT NULL,
    state               VARCHAR(20) NOT NULL DEFAULT 'NOT_LEARNED',  -- NOT_LEARNED / STILL_LEARNING / MASTERED
    consecutive_correct INT         NOT NULL DEFAULT 0,
    starred             BOOLEAN     NOT NULL DEFAULT FALSE,
    updated_at          TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_progress_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_progress_card FOREIGN KEY (card_id) REFERENCES cards (id),
    CONSTRAINT uq_progress_user_card UNIQUE (user_id, card_id),
    CONSTRAINT ck_progress_state CHECK (state IN ('NOT_LEARNED', 'STILL_LEARNING', 'MASTERED'))
);

-- "My study dashboard" scans (all progress of one user)
CREATE INDEX idx_progress_user_id ON card_progress (user_id);

-- Building a quiz for a deck: join cards of deck with user's progress
CREATE INDEX idx_progress_card_id ON card_progress (card_id);
