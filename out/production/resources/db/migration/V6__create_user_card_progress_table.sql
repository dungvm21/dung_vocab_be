-- V6: SRS (Spaced Repetition System) scheduling state per user and card.
-- Independent from card_progress (MCQ state machine); merge later if desired.
-- Column named interval_days because INTERVAL is a reserved word in PostgreSQL.

CREATE TABLE user_card_progress (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT            NOT NULL,
    card_id          BIGINT            NOT NULL,
    interval_days    INT               NOT NULL DEFAULT 0,      -- days until next review (0 = intra-session retry)
    repetition       INT               NOT NULL DEFAULT 0,      -- consecutive successful reviews
    ease_factor      DOUBLE PRECISION  NOT NULL DEFAULT 2.5,    -- SM-2 easiness, clamped [1.3, 2.8]
    next_review_date TIMESTAMPTZ       NOT NULL DEFAULT now(),  -- due when <= now
    status           VARCHAR(20)       NOT NULL DEFAULT 'NEW',  -- NEW / LEARNING / REVIEW / MASTERED
    updated_at       TIMESTAMPTZ       NOT NULL,

    CONSTRAINT fk_ucp_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ucp_card FOREIGN KEY (card_id) REFERENCES cards (id),
    CONSTRAINT uq_user_card_progress UNIQUE (user_id, card_id),
    CONSTRAINT ck_ucp_status CHECK (status IN ('NEW', 'LEARNING', 'REVIEW', 'MASTERED')),
    CONSTRAINT ck_ucp_ease CHECK (ease_factor >= 1.3 AND ease_factor <= 2.8)
);

-- Due-review queue scan: WHERE user_id = ? AND next_review_date <= now ORDER BY next_review_date
CREATE INDEX idx_ucp_user_next_review ON user_card_progress (user_id, next_review_date);
