-- V3: Create the cards table (terms & definitions inside decks).
-- Matches com.example.quizlet.entity.Card

CREATE TABLE cards (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term        VARCHAR(255)  NOT NULL,
    definition  VARCHAR(2000) NOT NULL,
    hint        VARCHAR(1000),
    deck_id     BIGINT        NOT NULL,

    CONSTRAINT fk_cards_deck FOREIGN KEY (deck_id) REFERENCES decks (id)
);

-- Deck lifecycle: load all cards of a deck
CREATE INDEX idx_cards_deck_id ON cards (deck_id);
