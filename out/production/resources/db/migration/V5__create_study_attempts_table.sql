-- V5: History of every answer a user gives during study (MCQ and future modes).
-- Powers analytics, wrong-answer review lists, and future SRS scheduling.

CREATE TABLE study_attempts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT      NOT NULL,
    card_id          BIGINT      NOT NULL,
    deck_id          BIGINT      NOT NULL,        -- denormalized for fast per-deck history
    mode             VARCHAR(20) NOT NULL,        -- MULTIPLE_CHOICE (more later: FLASHCARD, WRITING)
    is_correct       BOOLEAN     NOT NULL,
    selected_card_id BIGINT,                      -- which option the user picked (MCQ); NULL = skipped
    answered_at      TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_attempt_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_attempt_card FOREIGN KEY (card_id) REFERENCES cards (id),
    CONSTRAINT fk_attempt_deck FOREIGN KEY (deck_id) REFERENCES decks (id),
    CONSTRAINT fk_attempt_selected FOREIGN KEY (selected_card_id) REFERENCES cards (id),
    CONSTRAINT ck_attempt_mode CHECK (mode IN ('MULTIPLE_CHOICE'))
);

-- "My mistakes in deck X" review lists
CREATE INDEX idx_attempts_user_deck ON study_attempts (user_id, deck_id, is_correct);

-- Per-card answer history (SRS scheduling later)
CREATE INDEX idx_attempts_user_card ON study_attempts (user_id, card_id, answered_at);
